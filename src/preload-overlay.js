'use strict';
/**
 * Мост для окна выбора области.
 *
 * Это окно полноэкранное и показывает снимок экрана. Давать ему тот же
 * preload, что и окну настроек, нельзя: так оно получило бы чтение ключа
 * записи, смену адреса сервера и загрузку произвольного файла по
 * произвольно переданному пути. Любой посторонний скрипт, попавший в это
 * окно, выгрузил бы всё, до чего дотянется.
 *
 * Здесь ровно одна функция: сообщить выбранную область или отмену.
 */
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('puuush', {
  // Снимок экрана приходит сюда из главного процесса: окно обязано его
  // показать. Других каналов у этого окна нет и быть не должно.
  onFrame(cb) {
    ipcRenderer.on('puuush:frame', (_e, payload) => cb(payload));
  },

  submitRegion(rect) {
    ipcRenderer.send('puuush:region', rect === undefined ? null : rect);
  },
});